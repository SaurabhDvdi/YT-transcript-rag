@pytest.mark.asyncio
async def test_golden_contract_error_envelope_format(async_client: AsyncClient):
    resp = await async_client.get("/api/v1/non-existent-route")
    assert resp.status_code == 404
    data = resp.json()
    # Must have exact keys: success, error, requestId
    assert set(data.keys()) == {"success", "error", "requestId"}
    assert data["success"] is False
    assert set(data["error"].keys()) == {"code", "message"}
    assert data["error"]["code"] == "NOT_FOUND"
    assert "requestId" in data


